/// A block's own size, `bipoles/<name>/width` and `height` (in `bipoles/length`), when set: square
/// with its width, but for the generic two-ports; `None` for the other components.
pub fn size(cx: &mut Context, comp: &Component) -> Option<(f64, f64)> {
    if comp.class != Class::Blocks {
        return None;
    }
    let base = setting_name(comp.name.split('|').next().unwrap_or(comp.name));
    let mut get = |key: &str| {
        let s = setting(cx, &format!("bipoles/{base}/{key}")).unwrap_or_default();
        if s.trim().is_empty() {
            None
        } else {
            cx.number(Tokens::text(&s)).ok()
        }
    };
    let (w, h) = (get("width"), get("height"));
    if w.is_none() && h.is_none() {
        return None;
    }
    let width = w.unwrap_or(comp.width);
    let free = base.starts_with("twoport") || matches!(base, "tline" | "mstline");
    let height = h.unwrap_or(if free { comp.height } else { width * comp.height / comp.width });
    Some((width, height))
}

/// Where a block puts its `t=…` text (its middle), from the block's middle, in `bipoles/length`.
pub fn text(name: &str) -> [f64; 2] {
    match name {
        "bgenerator" => [-0.157, 0.0],
        "ngenerator" => [0.0, -0.1226],
        "qgenerator" => [-0.1575, 0.07],
        "amp" | "iamp" | "vamp" => [-0.084, 0.0],
        "amp|boxed" | "iamp|boxed" | "vamp|boxed" => [-0.0587, 0.0],
        _ => [0.0, 0.0],
    }
}

/// The blocks' names, for their size settings.
pub fn names() -> impl Iterator<Item = &'static str> {
    ALIASES.iter().map(|(k, _)| setting_name(k))
}

/// The name of a block in its size settings: `bipoles/tline/width` for `TL`.
pub fn setting_name(name: &str) -> &str {
    match name {
        "TL" => "tline",
        n => n,
    }
}

