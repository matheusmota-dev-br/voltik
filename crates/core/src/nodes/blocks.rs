/// Where lines to a round block stop: its circle, or its box when boxed (its first filled part).
pub fn border(n: &Node) -> Option<&'static [Op]> {
    let base = n.name.split('|').next().unwrap_or(n.name);
    if !matches!(base, "mixer" | "adder" | "oscillator" | "circulator") {
        return None;
    }
    n.parts.iter().find_map(|p| match p {
        Part::Fill(ops) => Some(*ops),
        _ => None,
    })
}

/// A block's inner drawing, the strokes after its outline: `blocks/inner thickness` times as wide,
/// in `blocks/inner color` (`default`: the node's).
pub fn inner(cx: &mut Context, n: &Node, mut paths: Vec<ShapePath>) -> Result<Vec<ShapePath>, Error> {
    if class(n.name) != Some("blocks") {
        return Ok(paths);
    }
    let k = crate::bipole::number(cx, "blocks/inner thickness", 1.0);
    let color = crate::bipole::setting(cx, "blocks/inner color")?;
    let color = (!color.is_empty() && color != "default").then_some(color);
    let mut outline = false;
    for p in paths.iter_mut() {
        if let ShapePaint::Stroke(w) = p.paint {
            if outline {
                p.paint = ShapePaint::Stroke(w * k);
                p.color = color.clone();
            }
            outline = true;
        }
    }
    Ok(paths)
}

/// A block's lateral anchors (`left up`…), `block left anchors pos` (and right) of the way from its
/// middle to its top.
pub fn lateral(cx: &mut Context, n: &Node, mut anchors: Vec<(String, Point)>, unit: f64) -> Vec<(String, Point)> {
    if class(n.name).is_none() {
        return anchors;
    }
    let (bottom, top) = (n.bounds[2] * unit, n.bounds[3] * unit);
    let left = crate::bipole::number(cx, "block left anchors pos", 0.5);
    let right = crate::bipole::number(cx, "block right anchors pos", 0.5);
    for (name, at) in anchors.iter_mut() {
        match name.as_str() {
            "left up" => at.y = left * top,
            "left down" => at.y = left * bottom,
            "right up" => at.y = right * top,
            "right down" => at.y = right * bottom,
            _ => {}
        }
    }
    anchors
}

/// The class of a block: `RF` for the antennas and microstrips, `blocks` for the others.
pub fn class(name: &str) -> Option<&'static str> {
    let base = name.split('|').next().unwrap_or(name);
    if !SHAPES.contains(&base) {
        return None;
    }
    Some(if base.contains("antenna") || base.starts_with("ms") || matches!(base, "waves" | "harmonics" | "tlinestub" | "match") { "RF" } else { "blocks" })
}
